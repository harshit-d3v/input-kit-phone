function extractRegionFromLocale(locale: string): string | undefined {
  const parts = locale.trim().replace(/_/g, '-').split('-');
  for (let index = 1; index < parts.length; index += 1) {
    const part = parts[index];
    if (part.length === 1) {
      break;
    }
    if (/^[A-Za-z]{2}$/.test(part)) {
      return part.toUpperCase();
    }
  }
  return undefined;
}

function normalizeFallback(fallback?: string): string | undefined {
  const trimmed = fallback?.trim();
  return trimmed ? trimmed.toUpperCase() : undefined;
}

/**
 * Infer a best-guess country ISO2 code from the browser's timezone and locale
 * without any network requests. Returns `fallback` on SSR or when unknown.
 */
export function detectBrowserCountry(fallback?: string): string | undefined {
  const normalizedFallback = normalizeFallback(fallback);

  if (typeof window === 'undefined') {
    return normalizedFallback;
  }

  try {
    const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone;
    const fromTimeZone = timeZone ? TIMEZONE_TO_COUNTRY[timeZone] : undefined;
    if (fromTimeZone && getCountryByCode(fromTimeZone)) {
      return fromTimeZone;
    }
  } catch {
    // Ignore restricted Intl environments.
  }

  if (typeof navigator !== 'undefined') {
    const languages = navigator.languages?.length
      ? navigator.languages
      : navigator.language
        ? [navigator.language]
        : [];
    for (const tag of languages) {
      const region = extractRegionFromLocale(tag);
      if (region && getCountryByCode(region)) {
        return region;
      }
    }
  }

  return normalizedFallback;
}
