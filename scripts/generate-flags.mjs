// Generates src/flag-data.ts from country-flag-icons 3x2 SVGs.
// country-flag-icons is a devDependency used only here, so the published package
// ships compact inline SVG data with zero CDN fetches or runtime dependencies.
//
// Run with: node scripts/generate-flags.mjs
import { getCountries } from 'libphonenumber-js'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const svgDir = join(rootDir, 'node_modules', 'country-flag-icons', '3x2')

const codes = Array.from(new Set([...getCountries(), 'AC', 'TA', 'BQ'])).sort()

const flags = {}
for (const code of codes) {
  const filePath = join(svgDir, `${code}.svg`)
  if (!existsSync(filePath)) continue

  const raw = readFileSync(filePath, 'utf8')
  const viewBoxMatch = raw.match(/viewBox="([^"]+)"/)
  const openTagEnd = raw.indexOf('>')
  const closeTagStart = raw.lastIndexOf('</svg>')
  if (openTagEnd === -1 || closeTagStart === -1) continue

  const body = raw
    .slice(openTagEnd + 1, closeTagStart)
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/>\s+</g, '><')
    .trim()

  flags[code] = {
    viewBox: viewBoxMatch?.[1] ?? '0 0 513 342',
    body,
  }
}

const banner = `// GENERATED by scripts/generate-flags.mjs. Do not edit by hand.
// Compact 3x2 SVG flag contents extracted from country-flag-icons so
// @input-kit/phone/flags works offline and on Windows without CDN fetches.
`

const body = `export interface FlagSvgData {
  viewBox: string
  body: string
}

export const FLAG_DATA: Record<string, FlagSvgData> = ${JSON.stringify(flags, null, 2)}
`

const out = join(rootDir, 'src', 'flag-data.ts')
writeFileSync(out, banner + '\n' + body)
console.log('wrote', out, '|', Object.keys(flags).length, 'flags')
